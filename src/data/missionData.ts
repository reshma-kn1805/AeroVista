// Helper to generate a unique MissionData when the user uploads their own video file
export function createMissionFromUpload(config: {
  name: string;
  description: string;
  profile: MissionProfile;
  videoMetadata?: DroneVideoMetadata;
  videoUrl?: string;
}): MissionData {
  const meta = config.videoMetadata || PRIMARY_DEMO_MISSION.video;
  const hash = Math.abs(
    config.name.split('').reduce((acc, char) => (acc * 31 + char.charCodeAt(0)) | 0, 0)
  );

  const durationSec = meta.durationSeconds || 120;
  const frames = meta.totalFrames || durationSec * 30;
  const keyframes = meta.keyframesCount || Math.max(12, Math.round(frames * 0.035));
  const points = 1500000 + (hash % 2500000);
  const meshFaces = Math.round(points * 0.45);
  const vertices = Math.round(points * 0.22);
  const qualityScore = Number((86.0 + (hash % 100) / 10).toFixed(1));

  // Base profile template
  let baseTemplate: MissionData;
  if (config.profile === 'Construction Monitoring') {
    baseTemplate = URBAN_DEMO_MISSION;
  } else if (config.profile === 'Infrastructure Inspection') {
    baseTemplate = config.name.toLowerCase().includes('substation') || config.name.toLowerCase().includes('power')
      ? SUBSTATION_DEMO_MISSION
      : QUARRY_DEMO_MISSION;
  } else if (config.profile === 'Agriculture/Land Analysis') {
    baseTemplate = AGRO_DEMO_MISSION;
  } else if (config.profile === 'Disaster Assessment') {
    baseTemplate = DISASTER_DEMO_MISSION;
  } else {
    baseTemplate = PRIMARY_DEMO_MISSION;
  }

  return {
    ...baseTemplate,
    id: `mission-user-${Date.now()}`,
    name: config.name,
    code: `AERO-${new Date().getFullYear()}-U${(hash % 900) + 100}`,
    date: new Date().toISOString().split('T')[0],
    profile: config.profile,
    status: 'Completed',
    video: {
      ...meta,
      filename: meta.filename || `${config.name.replace(/\s+/g, '_')}.mp4`,
      videoUrl: config.videoUrl,
    },
    pointsCount: points,
    verticesCount: vertices,
    meshFacesCount: meshFaces,
    coveragePct: Number((91.0 + (hash % 60) / 10).toFixed(1)),
    quality: {
      ...baseTemplate.quality,
      compositeScore: qualityScore,
    },
  };
}

